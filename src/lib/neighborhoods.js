export const getNeighborhoodsForCity = (city) => {
  const groups = neighborhoodGroups[city] || [];
  return groups.flatMap(g => g.neighborhoods);
};

export const getNeighborhoodCoordinates = (city, neighborhoodId) => {
  const all = getNeighborhoodsForCity(city);
  const n = all.find(n => n.id === neighborhoodId);
  return n ? { lat: n.lat, lng: n.lng } : null;
};
